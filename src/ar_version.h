// 实际改写的字节数（jmp rel32/abs 跳板长度）
constexpr size_t kPatchLen    = 15;

// Hook    = 会被改写序言，必须校验且必须成功
// Call    = 只被调用，校验以确保没有版本漂移（必需）
// Diagnostic = 只读诊断用，校验失败不影响安装（可选）
enum class TargetKind { Hook, Call, Diagnostic };

struct Target {
    uint32_t    rva;
    const char* fnName;
    const char* desc;
    TargetKind  kind;
    uint8_t     expect[kPrologueLen];
    // 函数长度（来自 .pdata）。这是比序言更硬的指纹：序言在 .text 里
    // 高度重复（0x425550 的 15 字节序言重复上千次），但"函数入口 + 长度"不重复。
    uint32_t    funcLen;
    // 长特征码：长度 = 该函数在 .text 内唯一所需的最短长度（含余量）。
    // 【用途是校验，不是定位】——版本漂移后 .text 重排，长签名必然失效；
    // 它只用来保证"同一个版本内，解出来的地址确实是那个函数"。
    uint32_t    sigLen;
    uint8_t     sig[64];
    // 同长度序言在 .text 里出现的次数。>1 说明"只看序言"无法唯一确定
    // 函数身份，必须靠 RVA 定位 —— 记录在这里以便排查时心里有数。
    uint32_t    prologueDupCount;
};

