// 二分查找（表已按 key 字典序排列）
inline const char* ArTechZh(const char* key) {
    if (!key) return nullptr;
    int lo = 0, hi = kArTechNamesCount - 1;
    while (lo <= hi) {
        const int mid = lo + (hi - lo) / 2;
        const int c = strcmp(key, kArTechNames[mid].key);
        if (c == 0) return kArTechNames[mid].zh;
        if (c < 0) hi = mid - 1;
        else lo = mid + 1;
    }
    return nullptr;
}

